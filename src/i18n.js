const KEY = 'admin_lang';
const attrs = ['placeholder', 'title'];
const orig = new WeakMap();
let on = false;

function pick() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved) return saved === 'ar';
  } catch {}
  const l = (navigator.language || '').toLowerCase();
  const tz = (Intl.DateTimeFormat().resolvedOptions().timeZone || '');
  return l.startsWith('ar') || tz === 'Asia/Riyadh';
}

function lookup(text) {
  const t = text.trim();
  const hit = ar[t];
  return hit ? text.replace(t, hit) : null;
}

function fixText(node) {
  const o = orig.get(node);
  if (on) {
    const base = o ?? node.nodeValue;
    const hit = lookup(base);
    if (hit && node.nodeValue !== hit) {
      orig.set(node, base);
      node.nodeValue = hit;
    }
  } else if (o !== undefined && ar[o.trim()] && node.nodeValue !== o) {
    node.nodeValue = o;
    orig.delete(node);
  }
}

function fixAttrs(el) {
  for (const a of attrs) {
    const v = el.getAttribute?.(a);
    const key = `__o_${a}`;
    if (on && v) {
      const base = el[key] ?? v;
      const hit = lookup(base);
      if (hit && hit !== v) {
        el[key] = base;
        el.setAttribute(a, hit);
      }
    } else if (!on && el[key]) {
      el.setAttribute(a, el[key]);
      delete el[key];
    }
  }
}

function walk(root) {
  if (root.nodeType === 3) return fixText(root);
  if (root.nodeType !== 1) return;
  fixAttrs(root);
  for (const c of root.childNodes) walk(c);
}

function apply() {
  document.documentElement.lang = on ? 'ar' : 'en';
  document.documentElement.dir = on ? 'rtl' : 'ltr';
  walk(document.body);
}

export function setArabic(v) {
  on = v;
  try {
    localStorage.setItem(KEY, v ? 'ar' : 'en');
  } catch {}
  apply();
  const b = document.getElementById('lang-toggle');
  if (b) b.textContent = on ? 'English' : 'العربية';
}

export function startI18n() {
  on = pick();
  const b = document.createElement('button');
  b.id = 'lang-toggle';
  b.type = 'button';
  b.textContent = on ? 'English' : 'العربية';
  b.onclick = () => setArabic(!on);
  document.body.appendChild(b);
  let busy = false;
  new MutationObserver((ms) => {
    if (busy) return;
    busy = true;
    for (const m of ms) {
      if (m.type === 'characterData') fixText(m.target);
      else if (m.type === 'attributes') fixAttrs(m.target);
      else for (const n of m.addedNodes) walk(n);
    }
    busy = false;
  }).observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: attrs,
  });
  apply();
}
